package com.tmz.aicode.ratelimit.enums;

/**
 * 限流维度。
 *
 * 不同维度只影响 Redis Key 的组成方式，底层都使用同一个分布式令牌桶实现。调用方可以
 * 根据接口用途选择全局保护、按登录用户隔离，或者按客户端地址隔离。
 */
public enum RateLimitType {

    /**
     * 接口级限流，同一个接口的所有调用者共享令牌桶。
     */
    API,

    /**
     * 用户级限流，每个登录用户拥有独立令牌桶；未登录时自动降级为 IP 维度。
     */
    USER,

    /**
     * IP 级限流，每个客户端地址拥有独立令牌桶。
     */
    IP
}
